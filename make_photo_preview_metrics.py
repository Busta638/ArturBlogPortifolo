"""
Generates photos/photo-darkness.js for the Photos landing page.

Put this file beside photos.html and run update-photo-preview-metrics.bat.

The generated JS is used to:
- avoid ugly overly-dense previews
- keep darker photos eligible when they still convert nicely
- rank a broad pool for faster/random preview selection
"""

import json
import sys
from pathlib import Path

try:
    from PIL import Image, ImageOps, ImageFilter
except ImportError:
    sys.exit("Pillow is not installed. Run: python -m pip install pillow")

EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".avif"}
DARK_LEVEL = 45

here = Path(__file__).resolve().parent

if (here / "photos.html").is_file():
    site_root = here
elif (here.parent / "photos.html").is_file():
    site_root = here.parent
else:
    site_root = here

if len(sys.argv) > 1:
    image_root = Path(sys.argv[1]).expanduser().resolve()
else:
    candidates = [
        site_root / "photos" / "photos",
        site_root / "photos",
    ]
    image_root = next((p for p in candidates if p.is_dir()), None)

if image_root is None or not image_root.is_dir():
    sys.exit(
        "Could not find the photo folder.\n"
        "Expected either:\n"
        f"  {site_root / 'photos' / 'photos'}\n"
        f"  {site_root / 'photos'}"
    )

output_file = site_root / "photos" / "photo-darkness.js"
output_file.parent.mkdir(parents=True, exist_ok=True)

paths = [
    p for p in sorted(image_root.rglob("*"))
    if p.is_file() and p.suffix.lower() in EXTENSIONS
]

def flat_pixels(img):
    # Pillow 12+ prefers get_flattened_data(); older installs use getdata().
    fn = getattr(img, "get_flattened_data", None)
    if callable(fn):
        return list(fn())
    return list(img.getdata())

def smoothstep(a, b, x):
    if b == a:
        return 1.0 if x >= b else 0.0
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3.0 - 2.0 * t)

print()
print("==========================================")
print("  PHOTO PREVIEW METRICS")
print("==========================================")
print()
print(f"Photo folder: {image_root}", flush=True)
print(f"Found {len(paths)} images.", flush=True)
print("Scanning preview suitability...", flush=True)

result = {}
skipped = 0

for index, path in enumerate(paths, start=1):
    try:
        with Image.open(path) as img:
            img = ImageOps.exif_transpose(img).convert("L")
            img.thumbnail((420, 420))

            hist = img.histogram()
            total = sum(hist)
            dark_share = (sum(hist[:DARK_LEVEL]) / total) if total else 0.0

            # Normalize exposure so the estimate is closer to what the browser
            # line-art filter does rather than just judging raw exposure.
            normalized = ImageOps.autocontrast(img, cutoff=(2, 1.5))
            edges = normalized.filter(ImageFilter.FIND_EDGES)
            blur = normalized.filter(ImageFilter.GaussianBlur(radius=max(2, normalized.width / 160)))

            base_px = flat_pixels(normalized)
            edge_px = flat_pixels(edges)
            blur_px = flat_pixels(blur)

            alpha_total = 0.0
            heavy_count = 0
            count = max(1, len(base_px))

            for lum, edge, blurred in zip(base_px, edge_px, blur_px):
                local_diff = abs(lum - blurred)

                # Edge + local contrast estimate. Broad flat dark regions contribute
                # far less than actual contours/details.
                detail = edge * 0.74 + local_diff * 0.98
                alpha = smoothstep(12, 54, detail)

                if lum > 226 and detail < 24:
                    alpha *= 0.18

                if edge > 66 or local_diff > 42:
                    alpha = max(alpha, 0.92)

                alpha *= 0.84

                alpha_total += alpha
                if alpha > 0.78:
                    heavy_count += 1

            result[path.relative_to(image_root).as_posix()] = {
                "dark": round(dark_share, 4),
                "ink": round(alpha_total / count, 4),
                "heavy": round(heavy_count / count, 4),
            }

    except Exception as error:
        skipped += 1
        print(f"Skipped: {path}")
        print(f"  {error}")

    if index == 1 or index % 25 == 0 or index == len(paths):
        print(f"Scanning {index} / {len(paths)}...", flush=True)

payload = (
    "/* Auto-generated by make_photo_preview_metrics.py. Do not edit by hand. */\n"
    "window.PHOTO_DARKNESS = "
    + json.dumps(result, indent=2, ensure_ascii=False)
    + ";\n"
)

output_file.write_text(payload, encoding="utf-8")

print()
print("DONE")
print(f"Saved JS file  : {output_file}")
print(f"Photos measured: {len(result)}")
if skipped:
    print(f"Skipped/errors : {skipped}")
