from __future__ import annotations

import json
import re
import unicodedata
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# Shared photo library:
#
# photos/
#   photos/
#     test/
#       image1.jpg
#       image2.jpg
#     future-event/
#       image1.jpg
#
# This script scans every event folder inside the nested /photos folder
# and writes ONE shared photos-data.js file.
LIBRARY_DIR = ROOT / "photos"
OUTPUT = ROOT / "photos-data.js"

EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".avif"}

try:
    from PIL import ExifTags, Image
except ImportError:
    Image = None
    ExifTags = None

DATE_IN_NAME = re.compile(
    r"(?P<y>20\d{2})[-_.]?(?P<m>0[1-9]|1[0-2])[-_.]?(?P<d>0[1-9]|[12]\d|3[01])"
)


def read_exif_date(path: Path) -> datetime | None:
    """Return the camera capture date when the image contains EXIF data."""
    if Image is None:
        return None

    try:
        with Image.open(path) as image:
            exif = image.getexif()

            if not exif:
                return None

            values = {
                ExifTags.TAGS.get(key, key): value
                for key, value in exif.items()
            }

            raw_date = (
                values.get("DateTimeOriginal")
                or values.get("DateTimeDigitized")
                or values.get("DateTime")
            )

            if raw_date:
                return datetime.strptime(str(raw_date), "%Y:%m:%d %H:%M:%S")
    except Exception:
        return None

    return None


def date_from_filename(path: Path) -> datetime | None:
    """Read dates from names such as 2026-07-30-car.jpg."""
    match = DATE_IN_NAME.search(path.stem)

    if not match:
        return None

    try:
        return datetime(
            int(match.group("y")),
            int(match.group("m")),
            int(match.group("d")),
        )
    except ValueError:
        return None


def photo_date(path: Path) -> datetime:
    """Prefer EXIF date, then filename date, then file modified date."""
    return (
        read_exif_date(path)
        or date_from_filename(path)
        or datetime.fromtimestamp(path.stat().st_mtime)
    )



def event_slug(value: str) -> str:
    """
    Create one stable event key for use by Selected, Travel and event pages.

    Example:
      ImportFest Aug 8 2026 Drift Event
      -> importfest-aug-8-2026-drift-event
    """
    normalized = unicodedata.normalize("NFKD", value)
    ascii_text = normalized.encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", ascii_text.lower()).strip("-")


def scan_library() -> list[dict[str, str]]:
    LIBRARY_DIR.mkdir(exist_ok=True)

    records: list[dict[str, str]] = []

    # Every direct subfolder of /photos is treated as one event.
    event_folders = sorted(
        [path for path in LIBRARY_DIR.iterdir() if path.is_dir()],
        key=lambda path: path.name.lower(),
    )

    for event_folder in event_folders:
        event_name = event_folder.name

        # Recursive so an event may contain its own subfolders if needed.
        files = [
            path
            for path in event_folder.rglob("*")
            if path.is_file() and path.suffix.lower() in EXTENSIONS
        ]

        files.sort(key=lambda path: (photo_date(path), path.name.lower()))

        for path in files:
            relative = path.relative_to(ROOT).as_posix()

            records.append(
                {
                    "src": relative,
                    "event": event_name,
                    "eventSlug": event_slug(event_name),
                    "date": photo_date(path).strftime("%Y-%m-%d"),
                    "file": path.name,
                }
            )

    return records


def write_javascript(records: list[dict[str, str]]) -> None:
    payload = "// Generated by update-photos.py. Do not edit by hand.\n"
    payload += "// event = original folder name; eventSlug = normalized matching key.\n"
    payload += f"// Total photos: {len(records)}\n\n"
    payload += "window.PHOTOS = "
    payload += json.dumps(records, indent=2)
    payload += ";\n\n"

    # Temporary compatibility aliases.
    # These let older pages keep working while the site is migrated.
    payload += "window.SELECTED_PHOTOS = window.PHOTOS;\n"
    payload += "window.TRAVEL_PHOTOS = window.PHOTOS;\n"

    OUTPUT.write_text(payload, encoding="utf-8")


def main() -> None:
    records = scan_library()
    write_javascript(records)

    print()
    print(f"Updated {OUTPUT.name} with {len(records)} photo(s).")

    if records:
        counts: dict[str, int] = {}
        for record in records:
            counts[record["event"]] = counts.get(record["event"], 0) + 1

        print()
        print("Events found:")
        for event_name, count in sorted(counts.items()):
            print(
                f"  {event_name}: {count} photo(s) "
                f"[eventSlug: {event_slug(event_name)}]"
            )
    else:
        print()
        print("No photos were found.")
        print(f"Put photos inside event folders under: {LIBRARY_DIR}")

    if Image is None:
        print()
        print("Note: Pillow is not installed, so dates use filenames or modified time.")
        print("For camera capture dates, run: py -m pip install pillow")


if __name__ == "__main__":
    main()
