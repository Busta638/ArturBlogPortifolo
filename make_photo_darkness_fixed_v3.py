"""
Generates photos/photo-darkness.js with THREE metrics per photo:

  dark  = raw share of very dark pixels in the original
  ink   = estimated share of the final image that would become visible ink
  heavy = estimated share that would become near-solid black ink

This makes photos.html able to reject visually heavy drawings even in file:// mode.

Put beside photos.html and run update-photo-darkness-v3.bat.
"""

import json
import sys
from pathlib import Path

try:
    from PIL import Image, ImageOps, ImageFilter, ImageStat
except ImportError:
    sys.exit("Pillow is not installed. Run: python -m pip install pillow")

DARK_LEVEL = 45
EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".avif"}

here = Path(__file__).resolve().parent
site_root = here if (here / "photos.html").is_file() else (here.parent if (here.parent / "photos.html").is_file() else here)

if len(sys.argv) > 1:
    image_root = Path(sys.argv[1]).expanduser().resolve()
else:
    candidates = [site_root / "photos" / "photos", site_root / "photos"]
    image_root = next((p for p in candidates if p.is_dir()), None)

if image_root is None:
    sys.exit("Could not find photos/photos or photos folder.")

output_file = site_root / "photos" / "photo-darkness.js"
output_file.parent.mkdir(parents=True, exist_ok=True)

paths = [p for p in sorted(image_root.rglob("*")) if p.is_file() and p.suffix.lower() in EXTENSIONS]

print(f"Photo folder: {image_root}", flush=True)
print(f"Found {len(paths)} images.", flush=True)
print("Scanning final-ink heaviness...", flush=True)

def smoothstep(a, b, x):
    if b == a:
        return 1.0 if x >= b else 0.0
    t = max(0.0, min(1.0, (x-a)/(b-a)))
    return t*t*(3-2*t)

result = {}
skipped = 0

for index, path in enumerate(paths, 1):
    try:
        with Image.open(path) as img:
            img = ImageOps.exif_transpose(img).convert("L")
            img.thumbnail((420, 420))

            # Raw darkness.
            hist = img.histogram()
            total = sum(hist)
            dark_share = sum(hist[:DARK_LEVEL]) / total if total else 0.0

            # Auto-level similar to browser renderer.
            img = ImageOps.autocontrast(img, cutoff=(2, 1.5))

            # Edge strength.
            edges = img.filter(ImageFilter.FIND_EDGES)
            edge_px = list(edges.getdata())

            # Local difference: compare original with a broader blur.
            blur = img.filter(ImageFilter.GaussianBlur(radius=max(2, img.width / 160)))
            a = list(img.getdata())
            b = list(blur.getdata())

            alphas = []
            heavy = 0

            for lum, blurred, edge in zip(a, b, edge_px):
                local_diff = abs(lum - blurred)

                # Similar philosophy as browser:
                # strong contour + local change = ink; broad flat areas fade.
                detail = edge * 0.72 + local_diff * 0.95
                alpha = smoothstep(12, 54, detail)

                # Very bright areas with weak detail disappear.
                if lum > 226 and detail < 24:
                    alpha *= 0.18

                # Crisp contours stay strong.
                if edge > 66 or local_diff > 42:
                    alpha = max(alpha, 0.92)

                # Slight global softening, matching page renderer.
                alpha *= 0.86
                alphas.append(alpha)
                if alpha > 0.78:
                    heavy += 1

            count = max(1, len(alphas))
            ink_share = sum(alphas) / count
            heavy_share = heavy / count

        relative = path.relative_to(image_root).as_posix()
        result[relative] = {
            "dark": round(dark_share, 4),
            "ink": round(ink_share, 4),
            "heavy": round(heavy_share, 4),
        }

    except Exception as error:
        skipped += 1
        print("Skipped:", path, error, flush=True)

    if index == 1 or index % 25 == 0 or index == len(paths):
        print(f"Scanning {index} / {len(paths)}...", flush=True)

payload = (
    "/* Auto-generated by make_photo_darkness_fixed_v3.py. Do not edit by hand. */\n"
    "window.PHOTO_DARKNESS = "
    + json.dumps(result, indent=2, ensure_ascii=False)
    + ";\n"
)
output_file.write_text(payload, encoding="utf-8")

bad_ink = sum(1 for v in result.values() if v["ink"] > 0.34 or v["heavy"] > 0.18)

print()
print("DONE")
print(f"Saved JS file  : {output_file}")
print(f"Photos measured: {len(result)}")
print(f"Rejected-ish   : {bad_ink} look too ink-heavy at current thresholds")
if skipped:
    print(f"Skipped/errors : {skipped}")
